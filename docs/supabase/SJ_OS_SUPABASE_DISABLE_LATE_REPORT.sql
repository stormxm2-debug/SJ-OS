-- ============================================================================
-- 지각 보고 공지 자동 게시 중지 (대표 지시, 2026-11-18)
--
-- 배경: 평일 09:05 KST에 'sj-late-report' 크론이 매일 announcements(공지)에
--       "MM월 DD일 지각 보고 (9시 기준)"를 자동 게시하고 있었다.
--       → 더 이상 지각 현황을 공지로 노출하지 않기로 함.
--
-- 조치: 크론 작업을 해제(unschedule). 출결 기록 자체는 그대로 유지되며,
--       출근 현황판(앱 내)에서는 계속 확인할 수 있다. 공지 자동 게시만 멈춘다.
--
-- 실행 위치: Supabase Dashboard > SQL Editor (총괄 세션 또는 대표님)
--            ※ 이미 이 세션에서 실행 완료됨(참고/재현용으로 보관).
-- ============================================================================

select cron.unschedule('sj-late-report');

